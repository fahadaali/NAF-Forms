import { getCloudflareContext } from "@opennextjs/cloudflare";
import { handleBackchannelLogout } from "naf-auth";
import { ssoConfig } from "@/lib/sso";

// إشعار الخروج الخلفي — المركز يُنهي جلسات عضوٍ في هذه المنصة.
//
// الخروج من هذه المنصة محليّ عمداً: من خرج من النماذج لم يطلب الخروج من
// الأربع الأخرى. أمّا الخروج من **المركز** فهو الباب نفسه — ومن أغلق البابَ
// لا يقبل أن تبقى غرفةٌ مفتوحة. وجلسة هذه المنصة مستقلّة عن جلسة المركز،
// وهو ما يجعل التنقّل فيها بلا مراجعةٍ في كل طلب، لكنه يعني أن خروج المركز
// لا يبلغها من نفسه: تبقى حيّةً حتى ينتهي رمزها، فيفتح صاحبُها رابط المنصة
// بعد خروجه فيدخل. وهذا المسار هو ما يُبلغها.
//
// **والمسار عامّ في `PUBLIC_EXACT`، وحراستُه التوقيع.** المنادي هو المركز
// خادماً لخادم، لا متصفّح له جلسة هنا يُحرَس بها. والإشعار رمزٌ موقّع بمفتاح
// المركز الذي تعرفه هذه المنصة أصلاً وتجلبه في `JWKS`، و`aud` فيه معرّفُها
// وحدها — فإشعارٌ لمنصة أخرى يُردّ، وإشعارٌ بلا توقيع صحيح يُردّ.
//
// **ومساره تحت `‎/auth/` لا `‎/api/` كالخروج.** المركز ينادي المنصات الخمس
// على مسار واحد يشتقّه من أصل كل منصة، فلو سمّت كلٌّ مسارها لصار في المركز
// جدولٌ ثانٍ يُحدَّث كلما أُضيفت منصة — وأولُ من يُنسى تحديثه هو الذي لا
// يخرج منه أحد.
export async function POST(req: Request): Promise<Response> {
  const { env } = await getCloudflareContext({ async: true });
  return handleBackchannelLogout(req, env, ssoConfig(env));
}
