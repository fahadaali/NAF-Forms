-- ============================================================
-- `viewer` يصير قارئاً فعلاً — ومن يحمله اليوم يُرفع إلى `editor`.
-- ============================================================

-- المنصة تعرض ثلاثة أدوار وتنفّذ اثنين: `requireAdmin` يفصل المسؤول عن
-- غيره، ولا فحص واحد يفرّق `editor` من `viewer`. فمن حمل «مستخدم (اطّلاع)»
-- ينشئ النماذج ويحرّرها ويحذف الردود.
--
-- ومع هذه الهجرة يصير الاسم صادقاً: حارسٌ في `src/middleware.ts` يمنع
-- الكتابة عن `viewer`.
--
-- **وهذا السطر يسبق الحارس ولا يتأخّر عنه.** الدور الافتراضي `viewer`،
-- فكلُّ من دخل ولم يُرقَّ يحمله. وتشغيلُ الحارس قبله ينزع الكتابة منهم
-- جميعاً في لحظة واحدة: نماذجُ قيد الإنشاء تُردّ بـ٤٠٣.
--
-- فيُرفعون إلى `editor` — وهو ما كانوا يملكونه فعلاً، فلا أحد يفقد شيئاً
-- ولا أحد يُمنح ما لم يكن له. و`viewer` يبقى لمن يُسنَد إليه بعد اليوم.
--
-- ويعمل مكرّراً بلا أثر: بعد أوّل تشغيل لا صفّ `viewer` يطابقه.
UPDATE members SET role = 'editor' WHERE role = 'viewer';
